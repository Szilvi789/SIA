#!/usr/bin/env node
// Download the pinned official Gitleaks binary and verify its published SHA256.
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const version = '8.30.1';
const downloads = {
  'win32-x64': ['windows_x64.zip', 'd29144deff3a68aa93ced33dddf84b7fdc26070add4aa0f4513094c8332afc4e'],
  'win32-arm64': ['windows_arm64.zip', 'b95f5e4f5c425cedca7ee203d9afd29597e692c4924a12ed42f970537c72cc0f'],
  'darwin-arm64': ['darwin_arm64.tar.gz', 'b40ab0ae55c505963e365f271a8d3846efbc170aa17f2607f13df610a9aeb6a5'],
  'darwin-x64': ['darwin_x64.tar.gz', 'dfe101a4db2255fc85120ac7f3d25e4342c3c20cf749f2c20a18081af1952709'],
  'linux-x64': ['linux_x64.tar.gz', '551f6fc83ea457d62a0d98237cbad105af8d557003051f41f3e7ca7b3f2470eb'],
  'linux-arm64': ['linux_arm64.tar.gz', 'e4a487ee7ccd7d3a7f7ec08657610aa3606637dab924210b3aee62570fb4b080']
};

function execute(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit', windowsHide: true });
  if (result.error || result.status !== 0) throw new Error(`${args[0] ?? command} could not complete.`);
}

function installHooks(root) {
  const existingPath = spawnSync('git', ['config', '--get', 'core.hooksPath'], { cwd: root, encoding: 'utf8', windowsHide: true });
  if (existingPath.stdout?.trim()) throw new Error('A custom core.hooksPath is configured; integrate .pre-commit-config.yaml with the existing hook manager first.');
  const gitHooks = spawnSync('git', ['rev-parse', '--git-path', 'hooks'], { cwd: root, encoding: 'utf8', windowsHide: true });
  if (gitHooks.status !== 0) throw new Error('Run hook setup in a Git clone.');
  for (const name of ['pre-commit', 'pre-push']) {
    const hook = resolve(root, gitHooks.stdout.trim(), name);
    if (existsSync(hook) && !readFileSync(hook, 'utf8').includes('File generated by pre-commit')) throw new Error(`Existing ${name} hook needs manual integration; nothing was overwritten.`);
  }
  const virtualEnv = join(root, '.local-tools', 'privacy', 'venv');
  const python = process.platform === 'win32' ? 'python' : 'python3';
  const localPython = join(virtualEnv, process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
  if (!existsSync(localPython)) execute(python, ['-m', 'venv', virtualEnv], root);
  const versionCheck = spawnSync(localPython, ['-m', 'pre_commit', '--version'], { cwd: root, encoding: 'utf8', windowsHide: true });
  if (versionCheck.status !== 0 || versionCheck.stdout.trim() !== 'pre-commit 4.7.0') execute(localPython, ['-m', 'pip', 'install', 'pre-commit==4.7.0'], root);
  execute(localPython, ['-m', 'pre_commit', 'validate-config', '.pre-commit-config.yaml'], root);
  execute(localPython, ['-m', 'pre_commit', 'install', '--hook-type', 'pre-commit', '--hook-type', 'pre-push'], root);
}

async function install() {
  const args = process.argv.slice(2);
  if (args.includes('--help')) {
    process.stdout.write('Usage: node scripts/install-privacy-tools.mjs [--hooks] [--archive /path/to/official-release.zip]\n--hooks installs pinned pre-commit into an isolated local venv and enables both hooks. Existing custom hooks are preserved.\n');
    return;
  }
  let archiveInput;
  let enableHooks = false;
  for (let index = 0; index < args.length; index++) {
    if (args[index] === '--hooks') enableHooks = true;
    else if (args[index] === '--archive' && args[index + 1]) archiveInput = resolve(args[++index]);
    else throw new Error('Unknown or incomplete setup option. Use --help.');
  }
  const selection = downloads[`${process.platform}-${process.arch}`];
  if (!selection) throw new Error('Install official Gitleaks 8.30.1 for this OS/architecture manually.');
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  // Install hook protection first, so download failure still leaves hooks failing closed.
  if (enableHooks) installHooks(root);
  const directory = join(root, '.local-tools', 'privacy');
  const executable = process.platform === 'win32' ? 'gitleaks.exe' : 'gitleaks';
  if (existsSync(join(directory, executable))) {
    const result = spawnSync(join(directory, executable), ['version'], { encoding: 'utf8', windowsHide: true });
    if (result.status === 0 && result.stdout.trim() === version) {
      process.stdout.write(`Gitleaks ${version} is already installed locally.\n`);
      return;
    }
    throw new Error('A different local Gitleaks binary already exists; review it before replacing it.');
  }
  const [suffix, expectedHash] = selection;
  const filename = `gitleaks_${version}_${suffix}`;
  const url = `https://github.com/gitleaks/gitleaks/releases/download/v${version}/${filename}`;
  let archive;
  if (archiveInput) archive = readFileSync(archiveInput);
  else {
    const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw new Error(`Official release download failed (${response.status}).`);
    archive = Buffer.from(await response.arrayBuffer());
  }
  if (createHash('sha256').update(archive).digest('hex') !== expectedHash) throw new Error('Gitleaks SHA256 verification failed; nothing was executed.');
  mkdirSync(directory, { recursive: true });
  const archivePath = join(directory, filename);
  writeFileSync(archivePath, archive, { mode: 0o600 });
  // Explicitly extract only the executable from the checksum-verified release archive.
  const result = spawnSync('tar', ['-xf', archivePath, '-C', directory, executable], { windowsHide: true, encoding: 'utf8' });
  if (result.error || result.status !== 0) throw new Error('Archive extraction failed; install tar or extract the verified release manually.');
  if (process.platform !== 'win32') chmodSync(join(directory, executable), 0o700);
  const installed = spawnSync(join(directory, executable), ['version'], { encoding: 'utf8', windowsHide: true });
  if (installed.status !== 0 || installed.stdout.trim() !== version) throw new Error('Gitleaks version validation failed.');
  process.stdout.write(`Installed verified Gitleaks ${version} in .local-tools/privacy (ignored by Git).\n`);
  process.stdout.write(enableHooks ? 'Local pre-commit and pre-push hooks are active.\n' : 'Enable both hooks: node scripts/install-privacy-tools.mjs --hooks\n');
  process.stdout.write('Audit: node scripts/privacy-audit.mjs\n');
}

try { await install(); }
catch (error) { process.stderr.write(`Privacy tool setup failed: ${error.message}\n`); process.exitCode = 1; }
